// Haversine Distance Calculator (km)
export function calculateDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a = 
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) * Math.cos(lat2 * (Math.PI / 180)) * 
    Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return parseFloat((R * c).toFixed(1));
}

// Fallback Nearest Labs Search Engine (25km, 50km, 100km radius)
export function getNearestFallbackLabs(userLat, userLng, radiusKm = 100) {
  return REAL_PAN_INDIA_LABORATORIES.map(lab => ({
    ...lab,
    distance: calculateDistanceKm(userLat, userLng, lab.lat, lab.lng)
  }))
  .filter(lab => lab.distance <= radiusKm)
  .sort((a, b) => a.distance - b.distance);
}
